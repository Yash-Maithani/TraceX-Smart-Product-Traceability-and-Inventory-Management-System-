import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import sharp from 'sharp';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const frontendRoot = path.resolve(__dirname, '..');
const manifestPath = path.resolve(frontendRoot, 'design-assets/backdrops.json');
const originalsDir = path.resolve(frontendRoot, 'design-assets/originals');
const outputDir = path.resolve(frontendRoot, 'src/assets/backdrops');
const tokensPath = path.resolve(frontendRoot, 'src/styles/tokens.css');

const REQUIRED_KEYS = [
  'auth',
  'auth-recovery',
  'dashboard',
  'batches',
  'fefo',
  'inspections',
  'dispatch',
  'qr',
  'trace-public',
  'team',
  'import',
  'notifications',
  'settings',
  'default'
];

const WIDTHS = [
  { width: 640, height: 360, budgetKb: 60 },
  { width: 1280, height: 720, budgetKb: 120 },
  { width: 1920, height: 1080, budgetKb: 250 }
];

const FORMATS = ['avif', 'webp', 'jpg'];

function parseHexToRgb(hex) {
  const clean = hex.replace('#', '').trim();
  const full =
    clean.length === 3
      ? clean
          .split('')
          .map((c) => c + c)
          .join('')
      : clean;
  const num = parseInt(full, 16);
  return {
    r: (num >> 16) & 255,
    g: (num >> 8) & 255,
    b: num & 255
  };
}

function extractTokenColors(cssText) {
  const blockMatch = cssText.match(/html\[data-palette="editorial"\]\[data-theme="light"\][^{]*\{([^}]+)\}/m);
  const block = blockMatch ? blockMatch[1] : cssText;
  const tokens = {};
  const propRegex = /(--[a-zA-Z0-9-]+)\s*:\s*(#[0-9a-fA-F]{3,6})/g;
  let m;
  while ((m = propRegex.exec(block)) !== null) {
    tokens[m[1]] = m[2];
  }
  return tokens;
}

function findOriginalFile(key) {
  const exts = ['.jpg', '.jpeg', '.png', '.webp', '.avif'];
  for (const ext of exts) {
    const candidate = path.join(originalsDir, `${key}${ext}`);
    if (fs.existsSync(candidate)) {
      return candidate;
    }
  }
  return null;
}

async function generateVariant(inputSource, isOriginal, width, height, format, outPath) {
  let pipeline;
  if (isOriginal) {
    pipeline = sharp(inputSource).resize(width, height, {
      fit: 'cover',
      position: 'centre'
    });
  } else {
    pipeline = sharp({
      create: {
        width,
        height,
        channels: 3,
        background: inputSource
      }
    });
  }

  if (format === 'avif') {
    pipeline = pipeline.avif({ quality: 68, effort: 2 });
  } else if (format === 'webp') {
    pipeline = pipeline.webp({ quality: 82 });
  } else {
    pipeline = pipeline.jpeg({ quality: 85, mozjpeg: true });
  }

  await pipeline.toFile(outPath);
  const stat = fs.statSync(outPath);
  return stat.size;
}

function buildGeneratedIndexTs(manifest) {
  const lines = [
    '// Auto-generated by scripts/prepare-backdrops.mjs — do not edit manually.',
    '',
    'export interface BackdropFormatSources {',
    '  640: string;',
    '  1280: string;',
    '  1920: string;',
    '}',
    '',
    'export interface BackdropAssetEntry {',
    '  key: string;',
    '  objectPosition: string;',
    '  placeholder: boolean;',
    '  avif: BackdropFormatSources;',
    '  webp: BackdropFormatSources;',
    '  jpg: BackdropFormatSources;',
    '}',
    '',
    'export const BACKDROP_ASSETS: Record<string, BackdropAssetEntry> = {'
  ];

  for (const entry of manifest) {
    lines.push(`  '${entry.key}': {`);
    lines.push(`    key: '${entry.key}',`);
    lines.push(`    objectPosition: '${entry.objectPosition || 'center center'}',`);
    lines.push(`    placeholder: ${Boolean(entry.placeholder)},`);
    for (const fmt of FORMATS) {
      lines.push(`    ${fmt}: {`);
      for (const { width } of WIDTHS) {
        lines.push(`      ${width}: new URL('./${entry.key}-${width}.${fmt}', import.meta.url).href,`);
      }
      lines.push('    },');
    }
    lines.push('  },');
  }

  lines.push('};');
  lines.push('');
  return lines.join('\n');
}

async function main() {
  if (!fs.existsSync(manifestPath)) {
    console.error(`Backdrop manifest not found at ${manifestPath}`);
    process.exit(1);
  }

  const cssText = fs.readFileSync(tokensPath, 'utf8');
  const tokenColors = extractTokenColors(cssText);
  const fallbackHex = tokenColors['--bg-muted'] || '#e6e3db';

  const manifest = JSON.parse(fs.readFileSync(manifestPath, 'utf8'));
  const manifestKeys = new Set(manifest.map((m) => m.key));
  for (const reqKey of REQUIRED_KEYS) {
    if (!manifestKeys.has(reqKey)) {
      console.error(`Missing required backdrop key '${reqKey}' in design-assets/backdrops.json`);
      process.exit(1);
    }
  }

  fs.mkdirSync(outputDir, { recursive: true });

  const tableRows = [];
  const budgetViolations = [];
  let manifestModified = false;

  for (let keyIdx = 0; keyIdx < manifest.length; keyIdx++) {
    const entry = manifest[keyIdx];
    const originalFile = findOriginalFile(entry.key);
    const isOriginal = Boolean(originalFile);

    if (!isOriginal && entry.placeholder !== true) {
      entry.placeholder = true;
      manifestModified = true;
    }

    const tokenName = entry.placeholderToken || '--bg-muted';
    const tokenHex = tokenColors[tokenName] || fallbackHex;
    const baseRgb = parseHexToRgb(tokenHex);
    const rgbColor = {
      r: Math.max(0, baseRgb.r - keyIdx),
      g: Math.max(0, baseRgb.g - keyIdx),
      b: Math.max(0, baseRgb.b - keyIdx)
    };

    for (const { width, height, budgetKb } of WIDTHS) {
      const budgetBytes = budgetKb * 1024;
      for (const format of FORMATS) {
        const fileName = `${entry.key}-${width}.${format}`;
        const outPath = path.join(outputDir, fileName);
        const bytes = await generateVariant(
          isOriginal ? originalFile : rgbColor,
          isOriginal,
          width,
          height,
          format,
          outPath
        );
        const sizeKb = (bytes / 1024).toFixed(2);
        const overBudget = bytes > budgetBytes;
        const status = overBudget ? 'OVER_BUDGET' : 'OK';

        if (overBudget) {
          budgetViolations.push(
            `${fileName}: ${sizeKb} KB (${bytes} B) exceeds budget of ${budgetKb} KB (${budgetBytes} B) for width ${width}px`
          );
        }

        tableRows.push({
          file: fileName,
          key: entry.key,
          sourceType: isOriginal ? 'original' : `placeholder (${tokenName})`,
          dimensions: `${width}x${height}`,
          format: format.toUpperCase(),
          bytes,
          sizeKb: `${sizeKb} KB`,
          budgetKb: `${budgetKb} KB`,
          status
        });
      }
    }
  }

  if (manifestModified) {
    fs.writeFileSync(manifestPath, `${JSON.stringify(manifest, null, 2)}\n`, 'utf8');
  }

  const indexTsPath = path.join(outputDir, 'index.ts');
  fs.writeFileSync(indexTsPath, buildGeneratedIndexTs(manifest), 'utf8');

  console.log('=== TraceX Backdrop Asset Pipeline (sharp) ===');
  console.log(
    `${'File'.padEnd(30)} | ${'Source'.padEnd(26)} | ${'Dimensions'.padEnd(10)} | ${'Size'.padStart(10)} | ${'Budget'.padStart(8)} | Status`
  );
  console.log('-'.repeat(102));
  for (const row of tableRows) {
    console.log(
      `${row.file.padEnd(30)} | ${row.sourceType.padEnd(26)} | ${row.dimensions.padEnd(10)} | ${row.sizeKb.padStart(10)} | ${row.budgetKb.padStart(8)} | ${row.status}`
    );
  }
  console.log('-'.repeat(102));
  console.log(`Total generated files: ${tableRows.length} (${manifest.length} keys x 3 widths x 3 formats)`);

  if (budgetViolations.length > 0) {
    console.error(`\nBackdrop budget check FAILED with ${budgetViolations.length} violation(s):`);
    for (const v of budgetViolations) {
      console.error(`  [BUDGET FAIL] ${v}`);
    }
    process.exit(1);
  }

  console.log('Backdrop preparation PASSED: all generated files are within size budgets.');
}

main().catch((err) => {
  console.error('Backdrop preparation failed:', err);
  process.exit(1);
});
